// 長文を読みやすくするため、文末の句点(。！？/ !?)の直後で改行を挿入する。
// マインドマップのノードやリスト表示で、改行のない一文の羅列を文単位で折り返すのに使う。
// ユーザーが自分で入れた改行・空行（段落間のスペース）・行頭スペースはそのまま残す。
export function breakBySentence(text: string): string {
  if (!text) return text
  return text
    // 「。」「！」「？」＋（任意の閉じ括弧/引用符）の直後、次が改行でも文末でもなければ改行を入れる
    .replace(/([。！？!?]+[」』）)\]】]*)(?![。！？!?」』）)\]】\n])/g, '$1\n')
    .replace(/\n+$/, '') // 末尾の改行だけ落とす（表示の下に余白が出ないように）
}
